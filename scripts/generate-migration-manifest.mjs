#!/usr/bin/env node
/**
 * Writes src/generated/migrations.ts: the list of migrations this build ships.
 *
 *   node scripts/generate-migration-manifest.mjs
 *
 * It runs before every build (the `prebuild` script), and the file it writes is
 * committed as well.
 *
 * Why it exists: /api/health reports whether the database a deployment talks
 * to has every migration the code expects. On a serverless host the
 * prisma/migrations folder is not something to rely on at runtime, so the list
 * is compiled into the build instead.
 *
 * Why the output is committed and not only generated: a checkout that has never
 * been built is still consistent, and a manifest that falls behind the folder
 * fails src/lib/migration-manifest.test.ts. The alternative is a health check
 * that compares the database against an older list and reports "aligned" on a
 * database missing the newest migration, which is the one mistake a check like
 * this must never make.
 */

import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs"
import path from "node:path"

const root = path.resolve(import.meta.dirname, "..")
const migrationsDir = path.join(root, "prisma", "migrations")
const outFile = path.join(root, "src", "generated", "migrations.ts")

// A migration is a folder with a migration.sql in it. migration_lock.toml and
// anything else left in the directory are not.
const names = readdirSync(migrationsDir, { withFileTypes: true })
  .filter((entry) => entry.isDirectory() && existsSync(path.join(migrationsDir, entry.name, "migration.sql")))
  .map((entry) => entry.name)
  .sort()

const content = [
  "// Generated by scripts/generate-migration-manifest.mjs. Do not edit by hand:",
  "// it is rewritten before every build from the folders in prisma/migrations.",
  "",
  "export const MIGRATIONS = [",
  ...names.map((name) => `  "${name}",`),
  "] as const",
  "",
].join("\n")

// Compared with line endings normalised, so a Windows checkout does not rewrite
// an identical file on every build.
const current = existsSync(outFile) ? readFileSync(outFile, "utf8").replace(/\r\n/g, "\n") : null

if (current === content) {
  console.log(`Migration manifest up to date: ${names.length} migration(s).`)
} else {
  mkdirSync(path.dirname(outFile), { recursive: true })
  writeFileSync(outFile, content)
  console.log(`Migration manifest written: ${names.length} migration(s).`)
}
